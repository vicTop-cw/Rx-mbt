# ============================================================================
# Test report generator (Windows PowerShell)
# Usage: powershell -ExecutionPolicy Bypass -File scripts/gen_test_report.ps1
# Outputs:
#   TEST_REPORT.md   - Markdown report (env / summary / per-package listing)
#   TEST_REPORT.json - JSON report (machine readable)
# Dependency: moon must be on PATH
# ============================================================================

$ErrorActionPreference = "Stop"
# Make sure we decode moon's UTF-8 stdout (PS 5.1 defaults to ANSI)
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$OutputEncoding = [System.Text.Encoding]::UTF8
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

# ---- 1. Environment info ----
$moonVersion = (moon version 2>&1 | Select-Object -First 1).Trim()
$date = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
$target = "wasm"

# ---- 2. Collect test outline (moon test --outline) ----
$outline = moon test --outline 2>&1
$tests = @()
foreach ($line in $outline) {
  # format:  1. vicTop-cw/RX-MBT/rx RX-MBT.mbt:274 index=0 name="of ..."
  if ($line -match '^\s*\d+\.\s+(\S+)\s+(\S+\.mbt):(\d+)\s+index=(\d+)\s+name="(.*)"\s*$') {
    $tests += [PSCustomObject]@{
      Package = $matches[1]
      File    = $matches[2]
      Line    = [int]$matches[3]
      Index   = [int]$matches[4]
      Name    = $matches[5]
    }
  }
}

# ---- 3. Run full test suite and parse summary ----
$testOutput = moon test 2>&1 | Out-String
$total = 0; $passed = 0; $failed = 0
if ($testOutput -match 'Total tests:\s*(\d+),\s*passed:\s*(\d+),\s*failed:\s*(\d+)') {
  $total  = [int]$matches[1]
  $passed = [int]$matches[2]
  $failed = [int]$matches[3]
}

# ---- 4. Group by package ----
$byPackage = $tests | Group-Object Package | ForEach-Object {
  [PSCustomObject]@{
    Package = $_.Name
    Count   = $_.Count
    Names   = @($_.Group | ForEach-Object { $_.Name })
  }
} | Sort-Object Package

# ---- 5. Markdown report ----
$md = New-Object System.Text.StringBuilder
[void]$md.AppendLine("# RX-MBT Test Report")
[void]$md.AppendLine("")
[void]$md.AppendLine("## Environment")
[void]$md.AppendLine("")
[void]$md.AppendLine("| Item | Value |")
[void]$md.AppendLine("|---|---|")
[void]$md.AppendLine("| Generated at | $date |")
[void]$md.AppendLine("| moon version | $moonVersion |")
[void]$md.AppendLine("| Test target | $target |")
[void]$md.AppendLine("| Total tests | $total |")
[void]$md.AppendLine("| Passed | $passed |")
[void]$md.AppendLine("| Failed | $failed |")
[void]$md.AppendLine("")
$status = if ($failed -eq 0) { "PASS (all green)" } else { "FAIL (see details)" }
[void]$md.AppendLine("**Result: $status**")
[void]$md.AppendLine("")
[void]$md.AppendLine("## Per-package stats")
[void]$md.AppendLine("")
[void]$md.AppendLine("| Package | Tests |")
[void]$md.AppendLine("|---|---|")
foreach ($p in $byPackage) {
  [void]$md.AppendLine("| $($p.Package) | $($p.Count) |")
}
[void]$md.AppendLine("| **Total** | **$total** |")
[void]$md.AppendLine("")
[void]$md.AppendLine("## Test listing")
[void]$md.AppendLine("")
foreach ($p in $byPackage) {
  [void]$md.AppendLine("### $($p.Package)")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("| # | Test name |")
  [void]$md.AppendLine("|---|---|")
  $i = 0
  foreach ($n in $p.Names) {
    $i++
    $escaped = $n.Replace("|", "\|")
    [void]$md.AppendLine("| $i | $escaped |")
  }
  [void]$md.AppendLine("")
}
[void]$md.AppendLine("---")
[void]$md.AppendLine("Generated by scripts/gen_test_report.ps1")

$md.ToString() | Out-File -FilePath (Join-Path $Root "TEST_REPORT.md") -Encoding utf8

# ---- 6. JSON report ----
$json = [PSCustomObject]@{
  generated_at = $date
  moon_version = $moonVersion
  target       = $target
  summary      = [PSCustomObject]@{ total = $total; passed = $passed; failed = $failed }
  packages     = @($byPackage | ForEach-Object {
    [PSCustomObject]@{ package = $_.Package; count = $_.Count; tests = @($_.Names) }
  })
} | ConvertTo-Json -Depth 5

$json | Out-File -FilePath (Join-Path $Root "TEST_REPORT.json") -Encoding utf8

Write-Output "Reports written:"
Write-Output "  TEST_REPORT.md"
Write-Output "  TEST_REPORT.json"
Write-Output "Summary: $total tests, $passed passed, $failed failed"
